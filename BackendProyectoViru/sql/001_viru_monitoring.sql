-- Schema changes needed by the monitoring / messaging code.
-- REVIEW BEFORE RUNNING. The app uses spring.jpa.hibernate.ddl-auto=validate, so Hibernate
-- will NOT create these: run this script yourself (psql or your IDE) before starting the app.
-- ASSUMED existing tables: usuario, agricultor, junta_regante (with region_id), region, dispositivo, transaccion.

-- 1) transaccion ---------------------------------------------------------------------------
-- A slot is created BEFORE the data arrives, so these two columns must accept NULL.
ALTER TABLE transaccion ALTER COLUMN recibido_nube_en DROP NOT NULL;
ALTER TABLE transaccion ALTER COLUMN guardado_bd_en  DROP NOT NULL;

-- One slot per device and expected time (also protects against duplicates).
ALTER TABLE transaccion
    ADD CONSTRAINT uq_transaccion_dispositivo_esperado UNIQUE (dispositivo_id, esperado_en);

-- Fails if old rows contain other values: check first with
--   SELECT DISTINCT estado FROM transaccion;
ALTER TABLE transaccion
    ADD CONSTRAINT ck_transaccion_estado
    CHECK (estado IN ('PENDIENTE', 'RECIBIDA', 'TARDIA', 'PERDIDA'));

CREATE INDEX ix_transaccion_pendientes
    ON transaccion (limite_en) WHERE estado = 'PENDIENTE';
CREATE INDEX ix_transaccion_dispositivo_esperado
    ON transaccion (dispositivo_id, esperado_en DESC);

-- 2) dispositivo ---------------------------------------------------------------------------
-- tipo must hold the TipoDispositivo enum names (all <= 20 chars).
ALTER TABLE dispositivo
    ADD CONSTRAINT ck_dispositivo_tipo
    CHECK (tipo IN ('CAUDALIMETRO_RIO', 'CAUDALIMETRO_CANAL', 'ESTACION_METEO'));
ALTER TABLE dispositivo
    ADD CONSTRAINT ck_dispositivo_tiempos
    CHECK (intervalo_segundos > 0 AND tolerancia_segundos >= 0);

-- 3) lectura: one row per measured variable of a transaction -------------------------------
CREATE TABLE lectura (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaccion_id bigint        NOT NULL REFERENCES transaccion (id),
    dispositivo_id bigint        NOT NULL REFERENCES dispositivo (id),
    variable       varchar(30)   NOT NULL,
    valor          numeric(14,4) NOT NULL,
    unidad         varchar(10),
    medido_en      timestamptz   NOT NULL
);

-- Same measurement delivered twice is rejected; also the key for "latest reading per device".
CREATE UNIQUE INDEX uq_lectura_dispositivo_variable_medido
    ON lectura (dispositivo_id, variable, medido_en);
CREATE INDEX ix_lectura_dispositivo_medido
    ON lectura (dispositivo_id, medido_en DESC);

-- 4) mensaje: written by an admin ----------------------------------------------------------
CREATE TABLE mensaje (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    autor_id         bigint       NOT NULL REFERENCES usuario (id),
    tipo             varchar(30)  NOT NULL
        CHECK (tipo IN ('HORA_RIEGO', 'ALERTA_BAJO_CAUDAL', 'ALERTA_ALTO_CAUDAL')),
    alcance          varchar(10)  NOT NULL CHECK (alcance IN ('JUNTA', 'REGION')),
    junta_regante_id integer      REFERENCES junta_regante (id),
    region_id        integer      REFERENCES region (id),
    riego_en         timestamptz,
    nota             varchar(500),
    creado_en        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_mensaje_destino CHECK (
        (alcance = 'JUNTA'  AND junta_regante_id IS NOT NULL AND region_id IS NULL) OR
        (alcance = 'REGION' AND region_id IS NOT NULL AND junta_regante_id IS NULL)),
    CONSTRAINT ck_mensaje_riego CHECK (
        (tipo = 'HORA_RIEGO' AND riego_en IS NOT NULL) OR
        (tipo <> 'HORA_RIEGO' AND riego_en IS NULL))
);

-- 5) entrega: one message delivered to one farmer, with its read status --------------------
CREATE TABLE entrega (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_id    bigint NOT NULL REFERENCES mensaje (id) ON DELETE CASCADE,
    agricultor_id bigint NOT NULL REFERENCES agricultor (id),
    leido_en      timestamptz,
    CONSTRAINT uq_entrega UNIQUE (mensaje_id, agricultor_id)
);
CREATE INDEX ix_entrega_agricultor ON entrega (agricultor_id, id DESC);

