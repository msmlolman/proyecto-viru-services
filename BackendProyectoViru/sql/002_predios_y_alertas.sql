BEGIN;
SET LOCAL search_path = app_pc4, public;

CREATE TABLE IF NOT EXISTS canal (
    dispositivo_id bigint PRIMARY KEY REFERENCES dispositivo(id),
    nombre varchar(120) NOT NULL
);

-- Los códigos CAN-01 a CAN-20 del laboratorio corresponden a las cabeceras N01 a N20 del plano PC2.
INSERT INTO canal (dispositivo_id, nombre)
SELECT d.id, p.nombre
FROM (VALUES
    ('CAN-01', 'Alayo'), ('CAN-02', 'Alfaro'), ('CAN-03', 'San Juan'),
    ('CAN-04', 'Caray'), ('CAN-05', 'Choloque'), ('CAN-06', 'Ciruelo'),
    ('CAN-07', 'Hierba Luisa'), ('CAN-08', 'Higuerón'), ('CAN-09', 'Huacapongo'),
    ('CAN-10', 'Marciano'), ('CAN-11', 'Napo'), ('CAN-12', 'Peña Azul'),
    ('CAN-13', 'Queneto'), ('CAN-14', 'San Nicolás'), ('CAN-15', 'Santa Mercedes'),
    ('CAN-16', 'Sarachaga'), ('CAN-17', 'Susanga'), ('CAN-18', 'Villegas'),
    ('CAN-19', 'Vinzos'), ('CAN-20', 'Viruly')
) AS p(codigo, nombre)
JOIN dispositivo d ON d.codigo = p.codigo AND d.tipo = 'CAUDALIMETRO_CANAL'
ON CONFLICT (dispositivo_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS predio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agricultor_id bigint NOT NULL REFERENCES agricultor(id),
    codigo varchar(32) NOT NULL UNIQUE,
    nombre varchar(120) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_predio_agricultor ON predio(agricultor_id);

CREATE TABLE IF NOT EXISTS predio_canal (
    predio_id bigint NOT NULL REFERENCES predio(id) ON DELETE CASCADE,
    canal_id bigint NOT NULL REFERENCES canal(dispositivo_id),
    PRIMARY KEY (predio_id, canal_id)
);
CREATE INDEX IF NOT EXISTS ix_predio_canal_canal ON predio_canal(canal_id, predio_id);

CREATE TABLE IF NOT EXISTS regla_caudal (
    canal_id bigint NOT NULL REFERENCES canal(dispositivo_id),
    simulada boolean NOT NULL,
    umbral_alto_lps numeric(14,4) NOT NULL CHECK (umbral_alto_lps > 0),
    retorno_lps numeric(14,4) NOT NULL CHECK (retorno_lps >= 0 AND retorno_lps < umbral_alto_lps),
    en_alerta boolean NOT NULL DEFAULT false,
    ultima_medicion timestamptz,
    PRIMARY KEY (canal_id, simulada)
);

ALTER TABLE lectura ADD COLUMN IF NOT EXISTS simulada boolean;

ALTER TABLE mensaje ALTER COLUMN autor_id DROP NOT NULL;
ALTER TABLE mensaje ADD COLUMN IF NOT EXISTS canal_id bigint REFERENCES canal(dispositivo_id);
ALTER TABLE mensaje ADD COLUMN IF NOT EXISTS simulada boolean NOT NULL DEFAULT false;
ALTER TABLE mensaje ADD COLUMN IF NOT EXISTS medido_en timestamptz;
ALTER TABLE mensaje ADD COLUMN IF NOT EXISTS caudal_lps numeric(17,4);
ALTER TABLE mensaje ADD COLUMN IF NOT EXISTS umbral_lps numeric(14,4);

-- PC4 se instaló con más de una variante de nombres para los CHECK de mensaje.
DO $$
DECLARE
    restriccion text;
BEGIN
    FOR restriccion IN
        SELECT c.conname
        FROM pg_constraint c
        WHERE c.conrelid = 'app_pc4.mensaje'::regclass AND c.contype = 'c'
          AND EXISTS (
              SELECT 1 FROM pg_attribute a
              WHERE a.attrelid = c.conrelid AND a.attnum = ANY(c.conkey)
                AND a.attname IN ('tipo', 'alcance', 'autor_id', 'junta_regante_id', 'region_id', 'riego_en')
          )
    LOOP
        EXECUTE format('ALTER TABLE app_pc4.mensaje DROP CONSTRAINT %I', restriccion);
    END LOOP;
END $$;

ALTER TABLE mensaje
    ADD CONSTRAINT ck_mensaje_tipo CHECK (tipo IN
        ('HORA_RIEGO', 'ALERTA_BAJO_CAUDAL', 'ALERTA_ALTO_CAUDAL', 'ALERTA_METEOROLOGICA')),
    ADD CONSTRAINT ck_mensaje_destino CHECK (
        (alcance = 'JUNTA' AND junta_regante_id IS NOT NULL AND region_id IS NULL AND canal_id IS NULL) OR
        (alcance = 'REGION' AND junta_regante_id IS NULL AND region_id IS NOT NULL AND canal_id IS NULL) OR
        (alcance = 'CANAL' AND junta_regante_id IS NULL AND region_id IS NULL AND canal_id IS NOT NULL)),
    ADD CONSTRAINT ck_mensaje_riego CHECK ((tipo = 'HORA_RIEGO') = (riego_en IS NOT NULL)),
    ADD CONSTRAINT ck_mensaje_origen CHECK (
        (alcance <> 'CANAL' AND autor_id IS NOT NULL AND medido_en IS NULL
            AND caudal_lps IS NULL AND umbral_lps IS NULL AND NOT simulada) OR
        (alcance = 'CANAL' AND autor_id IS NULL AND tipo = 'ALERTA_ALTO_CAUDAL'
            AND medido_en IS NOT NULL AND caudal_lps IS NOT NULL AND umbral_lps IS NOT NULL
            AND umbral_lps > 0 AND caudal_lps >= umbral_lps));

CREATE TABLE IF NOT EXISTS correo_alerta (
    entrega_id bigint PRIMARY KEY REFERENCES entrega(id) ON DELETE CASCADE,
    estado varchar(12) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'FALLIDO', 'OMITIDO')),
    intentos integer NOT NULL DEFAULT 0 CHECK (intentos >= 0),
    proximo_intento timestamptz NOT NULL DEFAULT now(),
    enviado_en timestamptz
);
CREATE INDEX IF NOT EXISTS ix_correo_alerta_pendiente
    ON correo_alerta(proximo_intento, entrega_id) WHERE estado = 'PENDIENTE';

DO $$
