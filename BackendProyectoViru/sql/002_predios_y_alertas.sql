    IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'viru_pc4_app') THEN
        GRANT SELECT ON canal, predio, predio_canal, regla_caudal, correo_alerta TO viru_pc4_app;
        GRANT INSERT, UPDATE ON predio, correo_alerta TO viru_pc4_app;
        GRANT INSERT, DELETE ON predio_canal TO viru_pc4_app;
        GRANT UPDATE (en_alerta, ultima_medicion) ON regla_caudal TO viru_pc4_app;
        GRANT USAGE ON SEQUENCE predio_id_seq TO viru_pc4_app;
    END IF;
END $$;
COMMIT;
